namespace YoutubeDownloadHelper.FakeYtDlp;

/// <summary>
/// The <c>--cookies</c> file. yt-dlp reads it at start and saves it back at exit; on save it loses every
/// <c>HttpOnly</c> flag (PLAN.md §5.7). Logged in means a <c>LOGIN_INFO</c> cookie is present.
/// </summary>
internal sealed class CookieJar
{
    private const string Header = "# Netscape HTTP Cookie File\n# This file is generated by yt-dlp.  Do not edit.\n\n";

    private readonly string _path;
    private readonly List<string[]> _cookies;

    private CookieJar(string path, List<string[]> cookies)
    {
        _path = path;
        _cookies = cookies;
    }

    public bool LoggedIn => _cookies.Any(c => c[5] == "LOGIN_INFO" && c[6].Length > 0);

    public static CookieJar? TryLoad(string? path)
    {
        if (path is null || !File.Exists(path))
        {
            return null;
        }

        var cookies = new List<string[]>();
        foreach (var raw in File.ReadAllLines(path))
        {
            var line = raw.StartsWith("#HttpOnly_", StringComparison.Ordinal) ? raw["#HttpOnly_".Length..] : raw;
            if (line.Length == 0 || line.StartsWith('#'))
            {
                continue;
            }

            var fields = line.Split('\t');
            if (fields.Length == 7)
            {
                cookies.Add(fields);
            }
        }

        return new CookieJar(path, cookies);
    }

    /// <summary>Appends <c>-rotated</c> to the value of each named cookie that exists.</summary>
    public void Rotate(IEnumerable<string> names)
    {
        var set = names.ToHashSet(StringComparer.Ordinal);
        foreach (var cookie in _cookies.Where(c => set.Contains(c[5])))
        {
            cookie[6] += "-rotated";
        }
    }

    public void Save() =>
        File.WriteAllText(_path, Header + string.Concat(_cookies.Select(c => string.Join('\t', c) + "\n")));
}
